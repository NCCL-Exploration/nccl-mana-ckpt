#!/usr/bin/env python3
"""Aggregate a campaign into the paper's tables.

    python3 experiments/lib/summarize.py <campaign_dir> [<out_dir>]

Reads <campaign_dir>/results.csv (one row per run), ckpts.csv (one row per
checkpoint) and torchsave.csv (one row per torch.save measurement), and
writes to <out_dir> (default: <campaign_dir>):
    summary.md          every table below, in Markdown
    overhead.csv        E1/E2: native vs. dmtcp (no checkpoint), per bench and layout
    micro_sizes.csv     E1: nccl_bench per message size, native / dmtcp / native_ref
    ckpt.csv            E1/E2/E3: checkpoint, resume and restart costs
    torchsave.csv       E3: torch.save / torch.load per width, policy and layout
    vs_torchsave.csv    E3: torch.save next to the DMTCP checkpoint of the same model
    p2p.csv             E4: pending point-to-point verdicts
    failures.csv        every run that did not pass
    tex/*.tex           the main tables as LaTeX (booktabs) tabulars

Stdlib only, so it runs on a login node without any module.
"""

import csv
import os
import statistics
import sys
from collections import defaultdict

HIGHER_IS_BETTER = {"pt_steps_per_s", "MBps_at_max", "is_mops", "cg_mops", "mg_mops"}
BW_BENCHES = {"nccl_bw", "nccl_bibw"}
APP_ORDER = ["is", "cg", "mg", "pytorch"]


def fnum(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def stats(values):
    v = [x for x in values if x is not None]
    if not v:
        return None
    return {
        "n": len(v),
        "mean": statistics.mean(v),
        "sd": statistics.stdev(v) if len(v) > 1 else 0.0,
        "min": min(v),
        "max": max(v),
    }


def mean(s):
    return None if s is None else s["mean"]


def sd(s):
    return None if s is None else s["sd"]


def fmt(s, digits=3):
    if s is None:
        return "-"
    if s["n"] == 1:
        return f"{s['mean']:.{digits}f}"
    return f"{s['mean']:.{digits}f} ± {s['sd']:.{digits}f}"


def tex(s, digits=2):
    if s is None:
        return "--"
    if s["n"] == 1:
        return f"{s['mean']:.{digits}f}"
    return f"{s['mean']:.{digits}f} $\\pm$ {s['sd']:.{digits}f}"


def scaled(s, k):
    return s and {x: (v * k if x != "n" else v) for x, v in s.items()}


def overhead_pct(native, other, higher_is_better):
    """Slowdown of `other` relative to `native`, in percent (positive = slower)."""
    if native is None or other is None or native["mean"] == 0 or other["mean"] == 0:
        return None
    if higher_is_better:
        return (native["mean"] / other["mean"] - 1.0) * 100.0
    return (other["mean"] / native["mean"] - 1.0) * 100.0


def pct(x):
    return "-" if x is None else f"{x:+.2f}%"


def ratio(a, b):
    if a is None or b is None or b["mean"] == 0:
        return None
    return a["mean"] / b["mean"]


def scale_key(r):
    return (int(r["nodes"]), int(r["gpus_per_node"]))


def scale_str(k):
    return f"{k[0]}x{k[1]} ({k[0] * k[1]} GPUs)"


def bench_order(b):
    base = "pytorch" if b.startswith("pytorch") else b
    if base in APP_ORDER:
        w = int(b[len("pytorch_w"):]) if b.startswith("pytorch_w") else 0
        return (0, APP_ORDER.index(base), w, b)
    if b.startswith("nccl_"):
        return (1, 0, 0, b)
    return (2, 0, 0, b)


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return list(csv.DictReader(f))


def write_csv(path, rows):
    if not rows:
        return
    keys = []
    for r in rows:
        keys += [k for k in r if k not in keys]
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)


def write_tex(path, cols, header, body, caption):
    with open(path, "w") as f:
        f.write(f"% {caption}\n% generated by experiments/lib/summarize.py\n")
        f.write(f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n")
        f.write(" & ".join(header) + " \\\\\n\\midrule\n")
        for row in body:
            f.write(" & ".join(row) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")


APP_LABEL = {"is": "NAS IS", "cg": "NAS CG", "mg": "NAS MG", "pytorch": "PyTorch DDP"}


def app_label(b):
    if b.startswith("pytorch_w"):
        return f"PyTorch DDP w{b[len('pytorch_w'):]}"
    return APP_LABEL.get(b, b.replace("_", "\\_"))


def write_figure_data(path, groups, vs):
    """pgfplots coordinates for the paper's figures (main.tex, Experimental
    Evaluation), one block per figure, to paste into the \\addplot lines."""
    out = ["% Data for the paper's figures; generated by experiments/lib/summarize.py.",
           "% Paste the coordinate lists into the matching \\addplot / yticklabels.", ""]
    layouts = sorted({k[1] for k in groups})

    def lay(s):
        return f"{s[0]}$\\times${s[1]}"

    def m(rows, key):
        return stats([fnum(r[key]) for r in rows])

    # fig:overhead -- one benchmark's metric, native vs. dmtcp, per layout.
    for b in [x for x in APP_ORDER if any(k[0] == x for k in groups)]:
        pts = [(s, m(groups.get((b, s, "native"), []), "metric"), m(groups.get((b, s, "dmtcp"), []), "metric"))
               for s in layouts]
        pts = [p for p in pts if p[1] and p[2]]
        if not pts:
            continue
        hib = groups[next(k for k in groups if k[0] == b)][0]["metric_name"] in HIGHER_IS_BETTER
        out.append(f"% fig:overhead, {app_label(b)} ({'higher' if hib else 'lower'} is better)")
        out.append("% xticklabels={" + ",".join(f"{{{s[0] * s[1]} GPUs\\\\{s[0]} node{'s' if s[0] > 1 else ''}}}" for s, _, _ in pts) + "}")
        out.append("%   native: coordinates {" + " ".join(f"(c{i},{n['mean']:.2f}) +- (0,{n['sd']:.2f})" for i, (s, n, d) in enumerate(pts)) + "};")
        out.append("%   dmtcp:  coordinates {" + " ".join(f"(c{i},{d['mean']:.2f}) +- (0,{d['sd']:.2f})" for i, (s, n, d) in enumerate(pts)) + "};")
        out.append("%   change: " + " ".join(f"c{i}={pct(None if overhead_pct(n, d, hib) is None else -overhead_pct(n, d, hib))}" for i, (s, n, d) in enumerate(pts)))
        out.append("")

    # fig:ckpt -- checkpoint split into NCCL-CR and the rest; restart split into rebuild and the rest.
    rows_ck, rows_rs = [], []
    for b in sorted({k[0] for k in groups if not k[0].startswith(("nccl_", "p2p_")) and k[0] != "torchsave"},
                    key=bench_order):
        for s in layouts:
            ck = groups.get((b, s, "ckpt_resume"), []) + groups.get((b, s, "ckpt_restart"), [])
            if ck:
                t, n_, img = m(ck, "ckpt_s"), m(ck, "nccl_drain_s"), m(ck, "image_bytes")
                if t:
                    rows_ck.append((f"{{{app_label(b)}, {lay(s)}}}", n_["mean"] if n_ else 0.0, t["mean"],
                                    img["mean"] / 2**30 if img else None))
            rs = groups.get((b, s, "ckpt_restart"), [])
            lat, rb = m(rs, "restart_latency_s"), m(rs, "restart_rebuild_s")
            rows_rs.append((f"{{{app_label(b)}, {lay(s)}}}", rb and rb["mean"], lat and lat["mean"]))
    if rows_ck:
        out.append("% fig:ckpt (a) Checkpoint")
        out.append("% yticklabels={" + ",".join(r[0] for r in rows_ck) + "}")
        out.append("%   NCCL-CR: coordinates {" + " ".join(f"({r[1]:.3f},{i})" for i, r in enumerate(rows_ck, 1)) + "};")
        out.append("%   rest:    coordinates {" + " ".join(f"({r[2] - r[1]:.3f},{i})" for i, r in enumerate(rows_ck, 1)) + "};")
        for i, r in enumerate(rows_ck, 1):
            img = "" if r[3] is None else f" \\textcolor{{vizink2}}{{\\,{r[3]:.1f}~GiB}}"
            out.append(f"%   \\node[font=\\scriptsize, text=vizink, anchor=west] at (axis cs:{r[2]:.3f},{i}) {{{r[2]:.1f}~s{img}}};")
        out.append("% fig:ckpt (b) Restart (same rows; a row without a passing restart is left out)")
        out.append("%   rebuild: coordinates {" + " ".join(f"({r[1]:.3f},{i})" for i, r in enumerate(rows_rs, 1) if r[2]) + "};")
        out.append("%   rest:    coordinates {" + " ".join(f"({r[2] - (r[1] or 0):.3f},{i})" for i, r in enumerate(rows_rs, 1) if r[2]) + "};")
        out.append("")

    # fig:network -- how much faster native_ref (OFI + GDR) is than native (socket).
    net = []
    for b in [x for x in APP_ORDER if any(k[0] == x for k in groups)] + ["nccl_latency", "nccl_bw"]:
        for s in layouts:
            n_, r = m(groups.get((b, s, "native"), []), "metric"), m(groups.get((b, s, "native_ref"), []), "metric")
            if not (n_ and r) or n_["mean"] == 0 or r["mean"] == 0:
                continue
            hib = groups[(b, s, "native")][0]["metric_name"] in HIGHER_IS_BETTER
            net.append((f"{{{app_label(b) if not b.startswith('nccl_') else b[5:].replace('_', ' ')}, {lay(s)}}}",
                        r["mean"] / n_["mean"] if hib else n_["mean"] / r["mean"]))
    if net:
        out.append("% fig:network: OFI reference speed-up over the socket transport (nccl_* at the largest size)")
        out.append("% yticklabels={" + ",".join(x[0] for x in net) + "}")
        out.append("%   coordinates {" + " ".join(f"({x[1]:.3f},{i})" for i, x in enumerate(net, 1)) + "};")
        out.append("")

    # New figure: torch.save vs. the transparent checkpoint of the same model.
    if vs:
        out.append("% fig:torchsave (new): per layout and width, torch.save (every rank) vs. DMTCP checkpoint, seconds")
        out.append("% symbolic x coords / labels: " + ", ".join(f"{r['nodes']}x{r['gpus_per_node']} w{r['width']}" for r in vs))
        out.append("%   torch.save: coordinates {" + " ".join(
            f"({i},{r['torchsave_job_save_s']:.3f})" for i, r in enumerate(vs) if r["torchsave_job_save_s"] is not None) + "};")
        out.append("%   DMTCP:      coordinates {" + " ".join(
            f"({i},{r['dmtcp_ckpt_s']:.3f})" for i, r in enumerate(vs) if r["dmtcp_ckpt_s"] is not None) + "};")
        out.append("")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def main():
    cdir = sys.argv[1] if len(sys.argv) > 1 else "."
    odir = sys.argv[2] if len(sys.argv) > 2 else cdir
    os.makedirs(os.path.join(odir, "tex"), exist_ok=True)
    rows = read_csv(os.path.join(cdir, "results.csv"))
    ts_rows = read_csv(os.path.join(cdir, "torchsave.csv"))
    if not rows and not ts_rows:
        sys.exit(f"no results in {cdir}")

    ok = [r for r in rows if r["status"] == "ok"]
    groups = defaultdict(list)
    for r in ok:
        groups[(r["bench"], scale_key(r), r["mode"])].append(r)
    benches = sorted({r["bench"] for r in rows}, key=bench_order)
    scales = sorted({scale_key(r) for r in rows} | {scale_key(r) for r in ts_rows})

    out = []
    name = os.environ.get("CAMPAIGN_NAME") or os.path.basename(os.path.abspath(cdir))
    out.append(f"# Campaign {name}\n")
    out.append(
        f"{len(rows)} runs, {len(ok)} ok. Values are mean ± sample std over successful "
        "repetitions. `native`: no DMTCP, the same NCCL settings as every DMTCP run; "
        "`dmtcp`: under dmtcp_launch with the NCCL and CUDA plugins, no checkpoint; "
        "`native_ref`: NCCL module defaults (production reference). Overhead is the "
        "slowdown of `dmtcp` relative to `native`.\n"
    )
    camp = os.path.join(cdir, "campaign.txt")
    if os.path.exists(camp):
        out.append("```\n" + open(camp).read().strip() + "\n```\n")

    # --- Runtime overhead (E1, E2) -------------------------------------------
    out.append("## Runtime overhead, no checkpoint (E1, E2)\n")
    out.append(
        "| Benchmark | Scale | Metric | native | dmtcp | overhead | native_ref | "
        "wall native (s) | wall dmtcp (s) |"
    )
    out.append("|---|---|---|---|---|---|---|---|---|")
    agg_over, tex_over = [], []
    for b in benches:
        if b.startswith("p2p_") or b == "torchsave":
            continue
        for s in scales:
            nat = groups.get((b, s, "native"), [])
            dm = groups.get((b, s, "dmtcp"), [])
            ref = groups.get((b, s, "native_ref"), [])
            if not (nat or dm or ref):
                continue
            mname = (nat or dm or ref)[0]["metric_name"]
            hib = mname in HIGHER_IS_BETTER
            sn, sdm, sr = (stats([fnum(r["metric"]) for r in g]) for g in (nat, dm, ref))
            wn, wd = (stats([fnum(r["wall_s"]) for r in g]) for g in (nat, dm))
            ov = overhead_pct(sn, sdm, hib)
            out.append(
                f"| {b} | {scale_str(s)} | {mname} | {fmt(sn)} | {fmt(sdm)} | {pct(ov)} | "
                f"{fmt(sr)} | {fmt(wn, 2)} | {fmt(wd, 2)} |"
            )
            agg_over.append({
                "bench": b, "nodes": s[0], "gpus_per_node": s[1], "nranks": s[0] * s[1],
                "metric": mname, "higher_is_better": int(hib),
                "native_mean": mean(sn), "native_sd": sd(sn), "native_n": sn and sn["n"],
                "dmtcp_mean": mean(sdm), "dmtcp_sd": sd(sdm), "dmtcp_n": sdm and sdm["n"],
                "native_ref_mean": mean(sr), "overhead_pct": ov,
                "wall_native_mean": mean(wn), "wall_dmtcp_mean": mean(wd),
            })
            tex_over.append([b.replace("_", "\\_"), f"{s[0]}$\\times${s[1]}", mname.replace("_", "\\_"),
                             tex(sn), tex(sdm), "--" if ov is None else f"{ov:+.1f}\\%"])
    out.append("")
    write_csv(os.path.join(odir, "overhead.csv"), agg_over)
    if tex_over:
        write_tex(os.path.join(odir, "tex", "overhead.tex"), "lllrrr",
                  ["Benchmark", "Layout", "Metric", "Native", "DMTCP", "Overhead"], tex_over,
                  "Runtime overhead without a checkpoint")

    # --- nccl_bench per message size (E1) -----------------------------------
    sizes = defaultdict(lambda: defaultdict(list))  # (bench, scale, mode) -> size -> [values]
    for r in ok:
        if not r["bench"].startswith("nccl_") or r["mode"] not in ("native", "dmtcp", "native_ref"):
            continue
        path = os.path.join(r["run_dir"], "sizes.csv")
        if not os.path.exists(path):
            continue
        with open(path) as f:
            for line in f:
                parts = line.strip().split(",")
                if len(parts) == 2 and fnum(parts[1]) is not None:
                    sizes[(r["bench"], scale_key(r), r["mode"])][int(parts[0])].append(float(parts[1]))
    size_rows = []
    for b in [x for x in benches if x.startswith("nccl_")]:
        hib = b in BW_BENCHES
        unit = "MB/s" if hib else "us"
        for s in scales:
            nat = sizes.get((b, s, "native"))
            dm = sizes.get((b, s, "dmtcp"))
            ref = sizes.get((b, s, "native_ref"), {})
            if not nat and not dm:
                continue
            nat, dm = nat or {}, dm or {}
            out.append(f"## E1 {b}, {scale_str(s)} ({unit})\n")
            out.append("| Size (B) | native | dmtcp | overhead | native_ref |")
            out.append("|---|---|---|---|---|")
            for sz in sorted(set(nat) | set(dm)):
                sn, sdm, sr = stats(nat.get(sz, [])), stats(dm.get(sz, [])), stats(ref.get(sz, []))
                ov = overhead_pct(sn, sdm, hib)
                out.append(f"| {sz} | {fmt(sn, 2)} | {fmt(sdm, 2)} | {pct(ov)} | {fmt(sr, 2)} |")
                size_rows.append({
                    "bench": b, "nodes": s[0], "gpus_per_node": s[1], "nranks": s[0] * s[1],
                    "size_bytes": sz, "unit": unit, "native_mean": mean(sn), "native_sd": sd(sn),
                    "dmtcp_mean": mean(sdm), "dmtcp_sd": sd(sdm), "native_ref_mean": mean(sr),
                    "overhead_pct": ov,
                })
            out.append("")
    write_csv(os.path.join(odir, "micro_sizes.csv"), size_rows)

    # --- Checkpoint / restart (E1, E2, E3) -------------------------------------
    out.append("## Checkpoint and restart (E1, E2, E3)\n")
    out.append(
        "`ckpt` = from `dmtcp_command -c` until the coordinator writes the restart script, "
        "i.e. every image is on disk (NCCL consensus, drain and teardown, CUDA checkpoint, "
        "image write). `nccl` = the NCCL plugin's share (max over ranks). `rounds` = most "
        "consensus rounds any checkpoint took. `resume rebuild` = communicator re-creation "
        "after a checkpoint the job survives. `restart latency` = `dmtcp_restart` until every "
        "rank has rebuilt its communicators; `restart total` = until the job completes.\n"
    )
    out.append(
        "| Benchmark | Scale | Mode | ok | ckpt (s) | nccl (s) | rounds | image total (GiB) | "
        "image/rank (MiB) | write (MiB/s) | resume rebuild (s) | restart latency (s) | "
        "restart rebuild (s) | restart total (s) |"
    )
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    agg_ckpt, tex_ckpt = [], []
    ckpt_by = {}
    keys = ("ckpt_s", "nccl_drain_s", "image_bytes", "write_MBps", "resume_rebuild_s",
            "restart_latency_s", "restart_rebuild_s", "restart_total_s")
    for b in benches:
        if b.startswith("p2p_"):
            continue
        for s in scales:
            for m in sorted({r["mode"] for r in rows if r["mode"].startswith("ckpt_")}):
                allruns = [r for r in rows if r["bench"] == b and scale_key(r) == s and r["mode"] == m]
                if not allruns:
                    continue
                g = groups.get((b, s, m), [])
                col = {k: stats([fnum(r[k]) for r in g]) for k in keys}
                rounds = max([int(fnum(r.get("rounds_max")) or 0) for r in g], default=0)
                nr = s[0] * s[1]
                img_gib = scaled(col["image_bytes"], 1 / 2**30)
                img_rank = scaled(col["image_bytes"], 1 / 2**20 / nr)
                ckpt_by[(b, s, m)] = col
                out.append(
                    f"| {b} | {scale_str(s)} | {m} | {len(g)}/{len(allruns)} | "
                    f"{fmt(col['ckpt_s'], 2)} | {fmt(col['nccl_drain_s'])} | {rounds or '-'} | "
                    f"{fmt(img_gib, 2)} | {fmt(img_rank, 0)} | {fmt(col['write_MBps'], 0)} | "
                    f"{fmt(col['resume_rebuild_s'])} | {fmt(col['restart_latency_s'], 2)} | "
                    f"{fmt(col['restart_rebuild_s'])} | {fmt(col['restart_total_s'], 2)} |"
                )
                row = {"bench": b, "nodes": s[0], "gpus_per_node": s[1], "nranks": nr, "mode": m,
                       "runs": len(allruns), "ok": len(g), "rounds_max": rounds}
                for k, v in col.items():
                    row[k + "_mean"] = mean(v)
                    row[k + "_sd"] = sd(v)
                agg_ckpt.append(row)
                if not b.startswith("nccl_"):
                    lat = col["restart_latency_s"] if m.startswith("ckpt_restart") else col["resume_rebuild_s"]
                    tex_ckpt.append([b.replace("_", "\\_"), f"{s[0]}$\\times${s[1]}", m.replace("_", "\\_"),
                                     f"{len(g)}/{len(allruns)}", tex(col["ckpt_s"]),
                                     tex(col["nccl_drain_s"]), tex(img_rank, 0), tex(lat)])
    out.append("")
    write_csv(os.path.join(odir, "ckpt.csv"), agg_ckpt)
    if tex_ckpt:
        write_tex(os.path.join(odir, "tex", "ckpt.tex"), "lllrrrrr",
                  ["Benchmark", "Layout", "Mode", "OK", "Ckpt (s)", "NCCL (s)", "Image/rank (MiB)",
                   "Rebuild / restart (s)"], tex_ckpt,
                  "Checkpoint cost; last column: resume rebuild (resume) or restart latency (restart)")

    # --- torch.save (E3) ---------------------------------------------------------
    ts_ok = [r for r in ts_rows if r.get("ok") == "1"]
    tsg = defaultdict(list)
    for r in ts_ok:
        tsg[(scale_key(r), int(r["width"]), r["policy"])].append(r)
    ts_agg = []
    if ts_rows:
        out.append("## torch.save baseline (E3)\n")
        out.append(
            "Per save: `d2h` = copy of the state dict (model + SGD momentum) to host memory, "
            "`write` = torch.save of that copy, `fsync` = until it is on the filesystem; "
            "`job save` = barrier to barrier, the time the job is stopped. `job load` = "
            "torch.load to the GPU + load_state_dict, page cache dropped first. Each phase is "
            "the max over ranks; mean ± std over every save of every run.\n"
        )
        out.append(
            "| Scale | Width | Params | Policy | n | payload/rank (MiB) | d2h (s) | write (s) | "
            "fsync (s) | job save (s) | job load (s) | MiB/s per rank |"
        )
        out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for (s, w, p) in sorted(tsg):
            g = tsg[(s, w, p)]
            col = {k: stats([fnum(r[k]) for r in g]) for k in
                   ("payload_bytes_per_rank", "d2h_s", "write_s", "fsync_s", "save_s", "job_save_s",
                    "load_s", "job_load_s", "write_MBps_per_rank", "file_bytes_total")}
            out.append(
                f"| {scale_str(s)} | {w} | {int(g[0]['params']):,} | {p} | {len(g)} | "
                f"{fmt(scaled(col['payload_bytes_per_rank'], 1 / 2**20), 0)} | {fmt(col['d2h_s'])} | "
                f"{fmt(col['write_s'])} | {fmt(col['fsync_s'])} | {fmt(col['job_save_s'])} | "
                f"{fmt(col['job_load_s'])} | {fmt(col['write_MBps_per_rank'], 0)} |"
            )
            row = {"nodes": s[0], "gpus_per_node": s[1], "nranks": s[0] * s[1], "width": w,
                   "params": g[0]["params"], "policy": p, "n": len(g)}
            for k, v in col.items():
                row[k + "_mean"] = mean(v)
                row[k + "_sd"] = sd(v)
            ts_agg.append(row)
        bad = len(ts_rows) - len(ts_ok)
        if bad:
            out.append(f"\n{bad} torch.save measurement(s) failed the restore check and are excluded.")
        out.append("")
    write_csv(os.path.join(odir, "torchsave.csv"), ts_agg)

    # --- torch.save vs. the transparent checkpoint, model for model ------------
    vs, tex_vs = [], []
    pt_width = int(os.environ.get("PT_WIDTH", 4096))
    for (s, w, p) in sorted(tsg):
        if p != "all":
            continue
        bench = "pytorch" if w == pt_width else f"pytorch_w{w}"
        res = ckpt_by.get((bench, s, "ckpt_resume"))
        rst = ckpt_by.get((bench, s, "ckpt_restart"))
        if res is None and rst is None:
            bench = f"pytorch_w{w}"
            res = ckpt_by.get((bench, s, "ckpt_resume"))
            rst = ckpt_by.get((bench, s, "ckpt_restart"))
        if res is None and rst is None:
            continue
        g = tsg[(s, w, p)]
        g0 = tsg.get((s, w, "rank0"), [])
        save = stats([fnum(r["job_save_s"]) for r in g])
        save0 = stats([fnum(r["job_save_s"]) for r in g0])
        load = stats([fnum(r["job_load_s"]) for r in g])
        payload = stats([fnum(r["payload_bytes_per_rank"]) for r in g])
        ck = groups.get((bench, s, "ckpt_resume"), []) + groups.get((bench, s, "ckpt_restart"), [])
        ckpt = stats([fnum(r["ckpt_s"]) for r in ck])
        img = stats([fnum(r["image_bytes"]) for r in ck])
        img_rank = scaled(img, 1 / (s[0] * s[1]))
        lat = rst["restart_latency_s"] if rst else None
        row = {
            "nodes": s[0], "gpus_per_node": s[1], "nranks": s[0] * s[1], "width": w,
            "dmtcp_bench": bench, "torchsave_job_save_s": mean(save),
            "torchsave_rank0_job_save_s": mean(save0), "dmtcp_ckpt_s": mean(ckpt),
            "ckpt_over_torchsave": ratio(ckpt, save), "torchsave_job_load_s": mean(load),
            "dmtcp_restart_latency_s": mean(lat), "restart_over_load": ratio(lat, load),
            "torchsave_payload_MiB_per_rank": payload and payload["mean"] / 2**20,
            "dmtcp_image_MiB_per_rank": img_rank and img_rank["mean"] / 2**20,
            "image_over_payload": ratio(img_rank, payload),
        }
        vs.append(row)
        tex_vs.append([f"{s[0]}$\\times${s[1]}", str(w), tex(save), tex(ckpt),
                       "--" if row["ckpt_over_torchsave"] is None else f"{row['ckpt_over_torchsave']:.1f}$\\times$",
                       tex(load), tex(lat),
                       "--" if payload is None else f"{payload['mean'] / 2**20:.0f}",
                       "--" if img_rank is None else f"{img_rank['mean'] / 2**20:.0f}"])
    if vs:
        out.append("## torch.save vs. transparent checkpoint, same model (E3)\n")
        out.append(
            "torch.save: every rank saves its replica (policy `all`; `rank0` is the usual DDP "
            "practice). DMTCP: `ckpt` over the resume and restart runs of the same model and "
            "layout; restart latency from the restart runs. The DMTCP image holds the whole "
            "process (CUDA context, Python, NCCL, optimizer), torch.save only the tensors.\n"
        )
        out.append(
            "| Scale | Width | torch.save all (s) | torch.save rank0 (s) | DMTCP ckpt (s) | ckpt / save | "
            "torch.load (s) | DMTCP restart (s) | restart / load | payload/rank (MiB) | "
            "image/rank (MiB) | image / payload |"
        )
        out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")

        def f(x, d=3):
            return "-" if x is None else f"{x:.{d}f}"

        for r in vs:
            out.append(
                f"| {r['nodes']}x{r['gpus_per_node']} | {r['width']} | {f(r['torchsave_job_save_s'])} | "
                f"{f(r['torchsave_rank0_job_save_s'])} | {f(r['dmtcp_ckpt_s'])} | "
                f"{f(r['ckpt_over_torchsave'], 1)} | {f(r['torchsave_job_load_s'])} | "
                f"{f(r['dmtcp_restart_latency_s'])} | {f(r['restart_over_load'], 1)} | "
                f"{f(r['torchsave_payload_MiB_per_rank'], 0)} | {f(r['dmtcp_image_MiB_per_rank'], 0)} | "
                f"{f(r['image_over_payload'], 1)} |"
            )
        out.append("")
        write_tex(os.path.join(odir, "tex", "vs_torchsave.tex"), "llrrrrrrr",
                  ["Layout", "Width", "torch.save (s)", "DMTCP ckpt (s)", "Ratio", "torch.load (s)",
                   "DMTCP restart (s)", "Payload/rank (MiB)", "Image/rank (MiB)"], tex_vs,
                  "Application-level torch.save vs. transparent checkpoint of the same job")
    write_csv(os.path.join(odir, "vs_torchsave.csv"), vs)

    # --- Pending point-to-point (E4) --------------------------------------------
    p2p = [r for r in rows if r["bench"].startswith("p2p_")]
    p2p_rows, tex_p2p = [], []
    if p2p:
        out.append("## Checkpoints with pending point-to-point operations (E4)\n")
        out.append(
            "PASS = the run verified (every receiver got its sender's data, before and after the "
            "checkpoint) and no `[NCCL Drain]` line appeared, i.e. the checkpoint waited for the "
            "missing counterpart instead of completing the other side with a dummy message.\n"
        )
        out.append("| Scenario | Scale | Mode | Verdict | Status | ckpt (s) | rounds | drained |")
        out.append("|---|---|---|---|---|---|---|---|")
        for r in sorted(p2p, key=lambda r: (r["bench"], scale_key(r), r["mode"])):
            drained = int(fnum(r.get("drained")) or 0)
            verdict = "PASS" if r["status"] == "ok" and drained == 0 else "FAIL"
            out.append(
                f"| {r['bench'][4:]} | {scale_str(scale_key(r))} | {r['mode']} | {verdict} | "
                f"{r['status']} | {r['ckpt_s'] or '-'} | {r.get('rounds_max') or '-'} | {drained} |"
            )
            p2p_rows.append({"scenario": r["bench"][4:], "nodes": r["nodes"],
                             "gpus_per_node": r["gpus_per_node"], "mode": r["mode"],
                             "verdict": verdict, "status": r["status"], "ckpt_s": r["ckpt_s"],
                             "rounds_max": r.get("rounds_max"), "drained": drained})
            tex_p2p.append([r["bench"][4:].replace("_", "-"), f"{r['nodes']}$\\times${r['gpus_per_node']}",
                            r["mode"].replace("_", "\\_"), verdict, r["ckpt_s"] or "--"])
        out.append("")
        write_tex(os.path.join(odir, "tex", "p2p.tex"), "lllll",
                  ["Scenario", "Layout", "Mode", "Verdict", "Ckpt (s)"], tex_p2p,
                  "Checkpoints taken while a point-to-point operation lacks its counterpart")
    write_csv(os.path.join(odir, "p2p.csv"), p2p_rows)

    # --- Failures ----------------------------------------------------------------
    bad = [r for r in rows if r["status"] != "ok"]
    fail_rows = []
    if bad:
        out.append("## Failed runs\n")
        out.append("| Benchmark | Scale | Mode | Rep | Status | First error | Run dir |")
        out.append("|---|---|---|---|---|---|---|")
        for r in bad:
            fe = ""
            p = os.path.join(r["run_dir"], "first_error.txt")
            if os.path.exists(p):
                fe = open(p, errors="replace").read().strip().replace("|", "/")[:160]
            out.append(f"| {r['bench']} | {scale_str(scale_key(r))} | {r['mode']} | {r['rep']} | "
                       f"{r['status']} | {fe} | {r['run_dir']} |")
            fr = {k: r[k] for k in ("bench", "nodes", "gpus_per_node", "mode", "rep", "status", "run_dir")}
            fr["first_error"] = fe
            fail_rows.append(fr)
        out.append("")
    skipped = os.path.join(cdir, "skipped.txt")
    if os.path.exists(skipped):
        lines = open(skipped).read().strip().splitlines()
        if lines:
            out.append(f"## Skipped runs ({len(lines)}, did not fit the job's time left)\n")
            out += [f"- {x}" for x in lines]
            out.append("")
    write_csv(os.path.join(odir, "failures.csv"), fail_rows)

    write_figure_data(os.path.join(odir, "tex", "figure_data.tex"), groups, vs)

    with open(os.path.join(odir, "summary.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
